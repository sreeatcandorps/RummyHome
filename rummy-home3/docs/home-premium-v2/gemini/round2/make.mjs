#!/usr/bin/env node
/**
 * Renders EZ Score: Rummy — Home Premium v2 Round 2 mockups (6 switchable themes, light & dark).
 * Produces single full-size PNGs only (no combined sheets):
 *   - 6 themes x 2 modes at 1236 x 2745 (Pixel 6 at 3x)
 *   - 2 small-phone renders at 1080 x 2340 (360 x 780 dp at 3x, font scale 1.3) for the two best
 *
 * Usage:
 *   node rummy-home3/docs/home-premium-v2/gemini/round2/make.mjs
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PARENT = path.resolve(HERE, '..');
const APP = path.resolve(HERE, '..', '..', '..', '..');
const CACHE = path.join(PARENT, '.cache');
const FONTS = path.join(CACHE, 'fonts');
const CHROME = process.env.CHROME || '/usr/local/bin/google-chrome';

mkdirSync(FONTS, { recursive: true });

// 1. Ensure Google Fonts (OFL) exist in ../.cache/fonts/
const GF = 'https://raw.githubusercontent.com/google/fonts/main/ofl/';
const FONT_FILES = {
  'PlayfairDisplay.ttf': 'playfairdisplay/PlayfairDisplay%5Bwght%5D.ttf',
  'CormorantGaramond.ttf': 'cormorantgaramond/CormorantGaramond%5Bwght%5D.ttf',
  'Cinzel.ttf': 'cinzel/Cinzel%5Bwght%5D.ttf',
  'PlusJakartaSans.ttf': 'plusjakartasans/PlusJakartaSans%5Bwght%5D.ttf',
};
for (const [file, src] of Object.entries(FONT_FILES)) {
  const to = path.join(FONTS, file);
  if (existsSync(to)) continue;
  const res = await fetch(GF + src);
  if (!res.ok) throw new Error(`font ${file}: HTTP ${res.status}`);
  writeFileSync(to, Buffer.from(await res.arrayBuffer()));
  console.log('font', file);
}

// 2. Copy MaterialCommunityIcons from @expo/vector-icons
const vectorCandidates = [
  path.join(APP, 'node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons'),
  '/agent/repos/RummyHome/rummy-home3/node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons',
];
const VECTOR = vectorCandidates.find((p) => existsSync(p));
if (!VECTOR) throw new Error('run `npm ci` in rummy-home3 first so @expo/vector-icons is available');

copyFileSync(path.join(VECTOR, 'Fonts/MaterialCommunityIcons.ttf'), path.join(FONTS, 'MaterialCommunityIcons.ttf'));
const glyphs = JSON.parse(readFileSync(path.join(VECTOR, 'glyphmaps/MaterialCommunityIcons.json'), 'utf8'));
const ICON_NAMES = [
  'plus', 'podium', 'account-group', 'information-outline', 'help-circle-outline',
  'circle-medium', 'flag-checkered', 'lock-outline', 'crown-outline', 'shield-account-outline',
  'trophy-outline', 'account-multiple-outline', 'chevron-right', 'home-variant',
  'wifi-strength-4', 'signal-cellular-3', 'battery-80',
];
const icons = Object.fromEntries(ICON_NAMES.map((n) => {
  if (!glyphs[n]) throw new Error(`missing glyph: ${n}`);
  return [n, glyphs[n]];
}));
writeFileSync(
  path.join(HERE, 'src/icons.js'),
  `// Generated by make.mjs from @expo/vector-icons MaterialCommunityIcons.\nwindow.ICONS = ${JSON.stringify(icons, null, 1)};\n`,
);

// 3. Load playwright-core from ../.cache/
const require = createRequire(import.meta.url);
let chromium;
try {
  ({ chromium } = require(path.join(CACHE, 'node_modules/playwright-core')));
} catch {
  console.log('installing playwright-core into ../.cache …');
  execFileSync('npm', ['i', '--prefix', CACHE, '--no-audit', '--no-fund', '--no-save', 'playwright-core@1.49.1'], { stdio: 'inherit' });
  ({ chromium } = require(path.join(CACHE, 'node_modules/playwright-core')));
}

const PIXEL6 = { w: 412, h: 915, fs: 1 };
const SMALL = { w: 360, h: 780, fs: 1.3 };

const THEMES = [
  'jaipur-sandstone',
  'deccan-breeze',
  'navaratna-gold',
  'mulberry-zari',
  'seshachalam-ember',
  'jatara-indigo',
];

const FRAMES = [];
for (const d of THEMES) {
  FRAMES.push({ name: `${d}-light`, d, mode: 'light', ...PIXEL6 });
  FRAMES.push({ name: `${d}-dark`, d, mode: 'dark', ...PIXEL6 });
}
// Two best on the small phone (360 dp, text scale 1.3): best light + best dark
FRAMES.push({ name: 'deccan-breeze-light-small', d: 'deccan-breeze', mode: 'light', ...SMALL });
FRAMES.push({ name: 'navaratna-gold-dark-small', d: 'navaratna-gold', mode: 'dark', ...SMALL });

const browser = await chromium.launch({
  executablePath: CHROME,
  args: ['--no-sandbox', '--font-render-hinting=none', '--allow-file-access-from-files'],
});

const fileUrl = (file, params) => `${pathToFileURL(path.join(HERE, file)).href}?${new URLSearchParams(params)}`;
let failed = false;

for (const f of FRAMES) {
  const page = await browser.newPage({ viewport: { width: f.w, height: f.h }, deviceScaleFactor: 3 });
  const problems = [];
  page.on('console', (m) => { if (m.type() === 'error') problems.push(m.text()); });
  page.on('pageerror', (e) => problems.push(String(e)));

  await page.goto(fileUrl('home.html', { d: f.d, mode: f.mode, w: f.w, h: f.h, fs: f.fs }));
  await page.evaluate(() => Promise.all([
    document.fonts.ready,
    ...[...document.images].map((img) => img.decode().catch(() => {})),
  ]));
  await page.waitForTimeout(160);

  const report = await page.evaluate(() => window.audit());
  for (const c of report.cut) problems.push(`cut: ${c}`);
  for (const c of report.contrast) problems.push(`contrast ${c.ratio}:1 (${c.fg} on ${c.bg}): "${c.text}"`);

  const outPath = path.join(HERE, `${f.name}.png`);
  await page.locator('.phone').screenshot({ path: outPath });
  await page.close();

  const low = report.lowest ? ` · lowest contrast ${report.lowest.ratio}:1 ("${report.lowest.text}")` : '';
  console.log(`${problems.length ? 'FAIL' : 'ok  '} ${f.name}.png (${f.w * 3}x${f.h * 3})${low}`);
  for (const p of problems) console.log('     ', p);
  if (problems.length) failed = true;
}

await browser.close();
if (failed) process.exit(1);
