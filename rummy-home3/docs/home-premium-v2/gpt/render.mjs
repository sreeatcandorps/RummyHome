#!/usr/bin/env node
/**
 * Render the five requested Home mockups.
 *
 * From rummy-home3:
 *   npm ci
 *   node docs/home-premium-v2/gpt/render.mjs
 *
 * The renderer keeps its fonts and Playwright package in this folder's ignored
 * .cache directory. It uses the app's MaterialCommunityIcons font and glyph map.
 */
import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.resolve(HERE, "..", "..", "..");
const CACHE = path.join(HERE, ".cache");
const FONTS = path.join(CACHE, "fonts");
const CHROME = process.env.CHROME || "/usr/local/bin/google-chrome";
const APP_MODULES = process.env.APP_NODE_MODULES || path.join(APP, "node_modules");

mkdirSync(FONTS, { recursive: true });

const fontFiles = {
  "Manrope.ttf":
    "https://raw.githubusercontent.com/google/fonts/main/ofl/manrope/Manrope%5Bwght%5D.ttf",
  "Fraunces.ttf":
    "https://raw.githubusercontent.com/google/fonts/main/ofl/fraunces/Fraunces%5BSOFT%2CWONK%2Copsz%2Cwght%5D.ttf",
  "Newsreader.ttf":
    "https://raw.githubusercontent.com/google/fonts/main/ofl/newsreader/Newsreader%5Bopsz%2Cwght%5D.ttf",
};
for (const [name, url] of Object.entries(fontFiles)) {
  const target = path.join(FONTS, name);
  if (existsSync(target)) continue;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Could not fetch ${name}: HTTP ${response.status}`);
  writeFileSync(target, Buffer.from(await response.arrayBuffer()));
}

const vectorIcons = path.join(
  APP_MODULES,
  "@expo/vector-icons/build/vendor/react-native-vector-icons",
);
if (!existsSync(vectorIcons)) {
  throw new Error(
    "The app icon font is missing. Run `npm ci` in rummy-home3, or set APP_NODE_MODULES.",
  );
}
copyFileSync(
  path.join(vectorIcons, "Fonts/MaterialCommunityIcons.ttf"),
  path.join(FONTS, "MaterialCommunityIcons.ttf"),
);

const glyphMap = JSON.parse(
  readFileSync(path.join(vectorIcons, "glyphmaps/MaterialCommunityIcons.json"), "utf8"),
);
const iconNames = [
  "account-group",
  "account-multiple-outline",
  "battery-80",
  "cards-playing-outline",
  "chevron-right",
  "circle-medium",
  "crown-outline",
  "help-circle-outline",
  "home-variant",
  "information-outline",
  "plus",
  "podium",
  "signal-cellular-3",
  "wifi-strength-4",
];
const icons = Object.fromEntries(
  iconNames.map((name) => {
    if (!glyphMap[name]) throw new Error(`Unknown app icon: ${name}`);
    return [name, glyphMap[name]];
  }),
);
writeFileSync(
  path.join(HERE, "icons.js"),
  `// Generated by render.mjs from the icon font used by the app.\nwindow.ICONS = ${JSON.stringify(icons, null, 2)};\n`,
);

const require = createRequire(import.meta.url);
let chromium;
try {
  ({ chromium } = require(path.join(CACHE, "node_modules/playwright-core")));
} catch {
  execFileSync(
    "npm",
    ["install", "--prefix", CACHE, "--no-save", "--no-audit", "--no-fund", "playwright-core@latest"],
    { stdio: "inherit" },
  );
  ({ chromium } = require(path.join(CACHE, "node_modules/playwright-core")));
}

const frames = [
  { file: "mahal-light-games.png", direction: "mahal", mode: "light", w: 412, h: 915, fs: 1 },
  { file: "mahal-dark-games.png", direction: "mahal", mode: "dark", w: 412, h: 915, fs: 1 },
  { file: "peacock-light-games.png", direction: "peacock", mode: "light", w: 412, h: 915, fs: 1 },
  { file: "peacock-dark-games.png", direction: "peacock", mode: "dark", w: 412, h: 915, fs: 1 },
  { file: "mahal-small-games.png", direction: "mahal", mode: "light", w: 360, h: 780, fs: 1.3 },
];

// Every text/background combination used by the mockups. Rendering stops below 4.5:1.
const contrastPairs = {
  "mahal-light": [
    ["#281711", "#F3ECDF"], ["#2B1812", "#F8F1E5"], ["#66493C", "#F2E7D6"],
    ["#FFF7E7", "#5F1829"], ["#321C13", "#EADCC7"], ["#FFF4D8", "#5F1929"],
    ["#2B1A13", "#FFFAF1"], ["#675B52", "#FFFAF1"], ["#13482C", "#D8EADC"],
    ["#573A08", "#F1DFAD"], ["#3D270E", "#C69542"], ["#FFF5DF", "#501522"],
  ],
  "mahal-dark": [
    ["#F7ECDB", "#150E0F"], ["#FFF1DC", "#211517"], ["#D8C2A8", "#211517"],
    ["#FFF8E8", "#7D263A"], ["#FFF0D6", "#25191B"], ["#362107", "#E0B75F"],
    ["#FFF0DC", "#2A1E20"], ["#C7B9AD", "#2A1E20"], ["#D7F4E1", "#1E5038"],
    ["#FFE9AF", "#4B3518"], ["#321F06", "#C0913D"], ["#FFF5DF", "#6D2034"],
  ],
  "peacock-light": [
    ["#102F31", "#EDF1ED"], ["#FFFDF0", "#0A4143"], ["#CDDFDA", "#0A4143"],
    ["#FFFAF0", "#AA4725"], ["#123637", "#F8FAF4"], ["#FFF9E9", "#0E5555"],
    ["#153334", "#FBFCF7"], ["#536968", "#FBFCF7"], ["#17492E", "#D7E9DC"],
    ["#6D2E12", "#F4DDC4"], ["#FFF8E7", "#0C4446"], ["#FFF8E7", "#0B4547"],
  ],
  "peacock-dark": [
    ["#EFF5ED", "#07191A"], ["#FFFDF0", "#092D30"], ["#C6D9D5", "#092D30"],
    ["#251007", "#E68A58"], ["#EFF7ED", "#0C292B"], ["#251007", "#E48A57"],
    ["#F0F5EC", "#123033"], ["#BDCECA", "#123033"], ["#D9F5E2", "#1C5038"],
    ["#FFD9BD", "#53301F"], ["#251007", "#E39764"], ["#241007", "#D97645"],
  ],
};
const channel = (hex) =>
  [1, 3, 5].map((i) => {
    const value = Number.parseInt(hex.slice(i, i + 2), 16) / 255;
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  });
const luminance = (hex) => {
  const [r, g, b] = channel(hex);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
};
for (const [palette, pairs] of Object.entries(contrastPairs)) {
  for (const [foreground, background] of pairs) {
    const ratio = contrast(foreground, background);
    if (ratio < 4.5) {
      throw new Error(`${palette}: ${foreground} on ${background} is only ${ratio.toFixed(2)}:1`);
    }
  }
}

const browser = await chromium.launch({
  executablePath: CHROME,
  args: ["--no-sandbox", "--font-render-hinting=none", "--allow-file-access-from-files"],
});
for (const frame of frames) {
  const page = await browser.newPage({
    viewport: { width: frame.w, height: frame.h },
    deviceScaleFactor: 3,
  });
  const params = new URLSearchParams({
    direction: frame.direction,
    mode: frame.mode,
    w: String(frame.w),
    h: String(frame.h),
    fs: String(frame.fs),
  });
  await page.goto(`${pathToFileURL(path.join(HERE, "home.html")).href}?${params}`);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(100);

  const problems = await page.evaluate(() => {
    const phone = document.querySelector(".phone");
    const frameBox = phone.getBoundingClientRect();
    const issues = [];
    for (const element of phone.querySelectorAll("*")) {
      const box = element.getBoundingClientRect();
      const style = getComputedStyle(element);
      const text = element.childNodes.length === 1 && element.firstChild.nodeType === Node.TEXT_NODE
        ? element.textContent.trim()
        : "";
      if (text && element.scrollWidth > element.clientWidth + 1 && style.whiteSpace !== "normal") {
        issues.push(`cut text: ${text}`);
      }
      if (box.left < frameBox.left - 1 || box.right > frameBox.right + 1) {
        issues.push(`outside screen: ${element.className || element.tagName}`);
      }
    }
    return issues;
  });
  if (problems.length) throw new Error(`${frame.file}\n${problems.join("\n")}`);

  await page.locator(".phone").screenshot({ path: path.join(HERE, frame.file) });
  await page.close();
  console.log(`rendered ${frame.file} (${frame.w * 3}x${frame.h * 3})`);
}
await browser.close();
