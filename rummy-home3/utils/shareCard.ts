import { resultsCountLine, resultShortId, ResultStanding, sheetGameLabel } from '@/utils/results';
import {
  capSplit,
  DesignPlayer,
  evenLine,
  gamesLine,
  generatedByLine,
  Medal,
  moreLine,
  rankScores,
  RankedScores,
  resultInitials,
  resultLinkText,
  SHARE_SIDE_CAP,
} from '@/utils/resultsDesign';

export type ShareLine = {
  id: string;
  name: string;
  /** "#8 · RK" under the name. */
  sub?: string;
  /** "+970" */
  points: string;
  /** Gold / silver / bronze badge on the top three positive totals. */
  medal?: Medal;
};

/**
 * The one-page share image (WhatsApp): header, count line, the scores split in two
 * columns with medals, the games line, who generated it, and the link. Details (per
 * game, per round) never go on the image; they live behind the link and in the PDF.
 */
export type ShareCard = {
  brand: 'EZ Score: Rummy';
  title: string;
  /** Six-character result code, top right. */
  code?: string;
  /** "Saved Fri, Nov 13 · 9:58 PM", or the date alone for a preview. */
  date: string;
  /** "7 games · 12 players" */
  summary?: string;
  /** The screen's banner and warning lines, word for word. The picture never looks cleaner than the screen. */
  notes?: string[];
  positive: ShareLine[];
  negative: ShareLine[];
  /** "and 4 more · full list in the link below" when a column was cut at SHARE_SIDE_CAP. */
  moreLine?: string | null;
  /** "Even: Sree, Harish" */
  evenLine?: string | null;
  /** "Games S12, S13 · saved Fri, Nov 13 · 9:58 PM" */
  gamesLine?: string | null;
  /** "Generated by SK" — initials only, never the full name. */
  generatedBy?: string | null;
  /** "ezscore.mindweavetech.com/r/<id>" on a saved result; nothing on a preview. */
  link?: string | null;
  /** Last line: "Result ID · ABC123" on saved results, "Preview · not saved" before. */
  footer?: string;
};

export { SHARE_SIDE_CAP };

function toLine(row: RankedScores['positive'][number]): ShareLine {
  return { id: row.id, name: row.name, sub: row.sub || undefined, points: row.text, ...(row.medal ? { medal: row.medal } : {}) };
}

/** Standings (any kind) as the two-column share card; the results and the single-game pictures share this. */
export function buildScoresCard(input: {
  title: string;
  date: string;
  code?: string;
  standings: ResultStanding[];
  players?: DesignPlayer[];
  games?: { scores: Record<string, number> }[];
  summary?: string;
  notes?: string[];
  gamesLine?: string | null;
  generatedByName?: string | null;
  link?: string | null;
  footer?: string;
}): ShareCard {
  const players: DesignPlayer[] = input.players ?? input.standings.map((row) => ({ id: row.id, name: row.name }));
  const labels = resultInitials(players, input.games ?? []);
  const ranked = rankScores(input.standings, players, labels);
  const capped = capSplit(ranked);
  return {
    brand: 'EZ Score: Rummy',
    title: input.title,
    ...(input.code ? { code: input.code } : {}),
    date: input.date,
    ...(input.summary ? { summary: input.summary } : {}),
    ...(input.notes?.length ? { notes: input.notes } : {}),
    positive: capped.positive.map(toLine),
    negative: capped.negative.map(toLine),
    moreLine: moreLine(capped.moreCount, Boolean(input.link)),
    evenLine: evenLine(ranked.even),
    gamesLine: input.gamesLine ?? null,
    generatedBy: generatedByLine(input.generatedByName),
    link: input.link ?? null,
    ...(input.footer ? { footer: input.footer } : {}),
  };
}

/** The results picture for a saved result or a preview. */
export function buildResultsShareCard(input: {
  standings: ResultStanding[];
  players?: DesignPlayer[];
  games: { name: string; label?: string | null; scores: Record<string, number> }[];
  /** ISO time of the save (or of the preview). */
  createdAtLabel: string;
  resultId?: string | null;
  generatedByName?: string | null;
  notes?: string[];
  footer?: string;
}): ShareCard {
  const saved = Boolean(input.resultId);
  const labels = input.games.map((game) => sheetGameLabel(game));
  const playerCount = new Set(input.games.flatMap((game) => Object.keys(game.scores).filter((id) => id !== 'EX'))).size || input.standings.length;
  return buildScoresCard({
    title: 'Results',
    code: input.resultId ? resultShortId(input.resultId) : undefined,
    date: saved ? `Saved ${input.createdAtLabel}` : input.createdAtLabel,
    standings: input.standings,
    players: input.players,
    games: input.games,
    summary: resultsCountLine(input.games.length, playerCount),
    notes: input.notes,
    gamesLine: gamesLine(labels, saved ? 'saved' : 'shown', input.createdAtLabel),
    generatedByName: input.generatedByName,
    link: input.resultId ? resultLinkText(input.resultId) : null,
    footer: input.footer,
  });
}
